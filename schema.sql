create table if not exists public.social_posts (
    id bigint generated by default as identity primary key,
    external_id text unique,
    platform text not null default 'x',
    timestamp timestamptz not null,
    username text not null,
    text text not null,
    hashtags text default '',
    likes integer default 0,
    reposts integer default 0,
    replies integer default 0,
    followers integer default 0,
    source_url text,
    inserted_at timestamptz not null default now()
);

create index if not exists social_posts_timestamp_idx
    on public.social_posts (timestamp desc);

create index if not exists social_posts_platform_idx
    on public.social_posts (platform);

create index if not exists social_posts_username_idx
    on public.social_posts (username);
