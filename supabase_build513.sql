-- Build 5.13 / Build 13
-- Run once in Supabase SQL Editor.
-- Stores browser-independent 30-minute execution history and recipient-level
-- delivery state so GitHub Actions can avoid duplicate emails on retries.

create table if not exists public.monitoring_runs (
    id bigint generated by default as identity primary key,
    slot_key text not null unique,
    run_timestamp timestamptz not null default now(),
    source_records integer not null default 0,
    x_records integer not null default 0,
    news_records integer not null default 0,
    positive_pct double precision not null default 0,
    neutral_pct double precision not null default 0,
    negative_pct double precision not null default 0,
    alert_threshold double precision not null default 35,
    alert_triggered boolean not null default false,
    pdf_filename text,
    routine_delivered jsonb not null default '[]'::jsonb,
    alert_delivered jsonb not null default '[]'::jsonb,
    routine_email_sent integer not null default 0,
    alert_email_sent integer not null default 0,
    status text not null default 'processing',
    error text,
    inserted_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists monitoring_runs_run_timestamp_idx
    on public.monitoring_runs (run_timestamp desc);

-- The background worker uses the service/secret key, so no public write policy
-- is required. The table remains protected by Supabase authentication/RLS setup.
